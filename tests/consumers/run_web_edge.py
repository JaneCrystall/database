#!/usr/bin/env python3
"""Qualify unchanged Next/Edge consumers against an owned local or Preview DB.

Only external Edge SDK providers are doubled. Next HTTP, Edge HTTP handlers,
Supabase Auth/SDK/PostgREST and metadata RPCs remain real. No business source or
existing env file is modified/read; temporary copies are removed on exit.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import socket
import subprocess
import tempfile
import time
from urllib.error import URLError
from urllib.request import urlopen

import runtime
from workspace_sources import sibling_source

HERE = Path(__file__).resolve().parent
WORKSPACE = HERE.parents[2]
NEXT = sibling_source(WORKSPACE, "web-app", "tiangong-ai-next")
EDGE = sibling_source(WORKSPACE, "edge-functions", "tiangong-ai-edge-function")


class ConsumerFailure(Exception):
    pass


def child_environment() -> dict[str, str]:
    allowed = {"PATH", "HOME", "TMPDIR", "DENO_DIR", "NODE_EXTRA_CA_CERTS"}
    return {**{key:value for key,value in os.environ.items() if key in allowed},
            "CI":"true", "NEXT_TELEMETRY_DISABLED":"1", "DENO_TLS_CA_STORE":"system"}


def source_copy(source: Path, destination: Path, facts: dict) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    content = source.read_bytes()
    destination.write_bytes(content)
    facts[str(source.relative_to(WORKSPACE))] = hashlib.sha256(content).hexdigest()


def available_port() -> int:
    with socket.socket() as connection:
        connection.bind(("127.0.0.1",0))
        return connection.getsockname()[1]


def stop_process(process: subprocess.Popen) -> None:
    if process.poll() is None:
        process.terminate()
        try:
            process.wait(timeout=15)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=10)


def completed_record(arguments: list[str], cwd: Path, env: dict, label: str, timeout: int = 180) -> dict:
    try:
        result = subprocess.run(arguments,cwd=cwd,env=env,capture_output=True,text=True,timeout=timeout)
    except (OSError,subprocess.TimeoutExpired):
        raise ConsumerFailure(f"{label} could not complete; provider/database diagnostics withheld.") from None
    if result.returncode:
        # Assertion messages are controlled labels; suppress all other output,
        # which can contain source dumps or upstream database diagnostic detail.
        for line in reversed(result.stdout.splitlines()):
            try:
                failure=json.loads(line)
            except ValueError:
                continue
            if isinstance(failure,dict) and failure.get("schema_version")==1 and failure.get("failed") is True and failure.get("consumer") in ("Next","Edge"):
                assertion=failure.get("assertion","")
                # Assertion labels are generated by our harness, not provider
                # responses. Reject anything outside the label alphabet.
                import re
                if isinstance(assertion,str) and re.fullmatch(r"[A-Za-z0-9 :/_()=-]{1,160}",assertion):
                    status=failure.get("http_status")
                    observed=f" (HTTP {status})" if isinstance(status,int) and 100<=status<=599 else ""
                    raise ConsumerFailure(f"{label} failed: {assertion}{observed}; raw diagnostics withheld.")
        raise ConsumerFailure(f"{label} failed (exit {result.returncode}); raw diagnostics withheld.")
    for line in reversed(result.stdout.splitlines()):
        try:
            value=json.loads(line)
        except ValueError:
            continue
        if isinstance(value,dict) and value.get("schema_version")==1:
            return value
    raise ConsumerFailure(f"{label} did not return a verification record.")


def run_next(target_file: Path, temporary: Path, facts: dict) -> dict:
    node=shutil.which("node")
    next_binary=NEXT/"node_modules/next/dist/bin/next"
    if not node or not next_binary.is_file():
        raise ConsumerFailure("Existing Next dependencies and Node are required.")
    app=temporary/"next"
    app.mkdir()
    (app/"node_modules").symlink_to(NEXT/"node_modules",target_is_directory=True)
    for relative in ["package.json", "tsconfig.json",
                     "lib/kb/resource-config.ts","lib/kb/resource-store.ts",
                     "lib/supabase/admin.ts","lib/supabase/service-role.ts","lib/server/env.ts",
                     "lib/supabase/env.ts","lib/supabase/server.ts",
                     "app/api/kb/resources/[collection]/route.ts",
                     "app/api/kb/resources/[collection]/[id]/route.ts"]:
        source_copy(NEXT/relative,app/relative,facts)
    # S9 executes the existing API-key/Jobs routes and their source dependencies.
    for relative in ["app/api/kb/admin/api-keys/route.ts",
                     "app/api/kb/admin/api-keys/[keyId]/revoke/route.ts",
                     "app/api/kb/admin/api-keys/[keyId]/rotate/route.ts",
                     "app/api/kb/admin/jobs/route.ts"]:
        source_copy(NEXT/relative,app/relative,facts)
    for source in sorted((NEXT/"lib/kb").rglob("*.ts")):
        source_copy(source,app/source.relative_to(NEXT),facts)
    source_copy(HERE/"worker_route.ts",app/"app/api/s9-workers/route.ts",facts)
    # The isolated app has only API routes. No consumer product UI or proxy is
    # replaced; their source is not needed to execute the actual route modules.
    (app/"next.config.mjs").write_text("export default {devIndicators:false};\n",encoding="utf-8")
    source_copy(HERE/"next_consumer.mjs",app/"next_consumer.mjs",facts)
    target=runtime.load_private(target_file)
    env=child_environment()
    env.update({"NEXT_PUBLIC_SUPABASE_URL":target["api_url"],
                "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY":target["publishable_key"],
                "SUPABASE_SERVICE_ROLE_KEY":target["service_role_key"]})
    port=available_port()
    base=f"http://127.0.0.1:{port}"
    # Output stays private and is never included in reports or errors.
    with (temporary/"next-runtime.log").open("w",encoding="utf-8") as log:
        process=subprocess.Popen([node,str(next_binary),"dev","--webpack","--hostname","127.0.0.1","--port",str(port)],cwd=app,env=env,stdout=log,stderr=subprocess.STDOUT)
        try:
            deadline=time.monotonic()+120
            while time.monotonic()<deadline:
                if process.poll() is not None:
                    raise ConsumerFailure("Next isolated runtime failed to start; diagnostics withheld.")
                try:
                    # Expected 401; an HTTP response establishes compiled real
                    # Route Handler readiness without granting access.
                    with urlopen(base+"/api/kb/resources/education",timeout=10) as response:
                        break
                except URLError as error:
                    if getattr(error,"code",None)==401:
                        break
                    time.sleep(0.25)
            else:
                raise ConsumerFailure("Next isolated runtime readiness timed out.")
            return completed_record([node,str(app/"next_consumer.mjs"),str(target_file),base],app,env,"Next consumer HTTP")
        finally:
            stop_process(process)


def run_edge(target_file: Path, temporary: Path, facts: dict) -> dict:
    deno=shutil.which("deno")
    if not deno:
        raise ConsumerFailure("Deno is required for actual Edge handler execution.")
    app=temporary/"edge"
    app.mkdir()
    for source in sorted((EDGE/"supabase/functions/_shared").glob("*.ts")):
        source_copy(source,app/"functions/_shared"/source.name,facts)
    for name in ["edu_search","esg_search","standard_search","sci_search","course_search"]:
        source_copy(EDGE/f"supabase/functions/{name}/index.ts",app/f"functions/{name}/index.ts",facts)
    source_copy(HERE/"edge_consumer.ts",app/"edge_consumer.ts",facts)
    source_copy(HERE/"external_mocks/providers.ts",app/"external_mocks/providers.ts",facts)
    (app/"external_mocks/runtime_types.ts").write_text("export {};\n",encoding="utf-8")
    mapping=json.loads((EDGE/"supabase/functions/deno.json").read_text())["imports"]
    for name in ["@aws-sdk/credential-provider-node","@opensearch-project/opensearch","@opensearch-project/opensearch/aws","@openai/openai","@pinecone-database/pinecone","@upstash/redis"]:
        mapping[name]="./external_mocks/providers.ts"
    mapping["@supabase/functions-js/edge-runtime.d.ts"]="./external_mocks/runtime_types.ts"
    (app/"deno.json").write_text(json.dumps({"imports":mapping,"nodeModulesDir":"none"}),encoding="utf-8")
    target=runtime.load_private(target_file)
    from urllib.parse import urlsplit
    hostname=urlsplit(target["api_url"]).hostname
    # Real DB HTTP and local requests only; provider classes cannot call live
    # services. npm/JSR module resolution may still download package sources.
    return completed_record([deno,"run","--no-check",f"--allow-net=127.0.0.1,localhost,{hostname}",
                             "--allow-env","--allow-read",str(app/"edge_consumer.ts"),str(target_file)],
                            app,child_environment(),"Edge consumer HTTP",timeout=240)


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target",required=True,help="Owned private target JSON including synthetic user and fixtures.")
    parser.add_argument("--only",choices=("next","edge","both"),default="both")
    parser.add_argument("--report",help="New receipt JSON path; credentials are never included.")
    args=parser.parse_args()
    target_file=Path(args.target).resolve()
    target=runtime.load_private(target_file)
    runtime.validate_target(target)
    if not target.get("user") or not target.get("fixtures"):
        raise ConsumerFailure("Synthetic fixture manifest and actor are required.")
    facts={}
    results=[]
    with tempfile.TemporaryDirectory(prefix="tiangong-db-web-edge-") as directory:
        temporary=Path(directory)
        if args.only in ("next","both"):
            results.append(run_next(target_file,temporary,facts))
        if args.only in ("edge","both"):
            results.append(run_edge(target_file,temporary,facts))
    receipt={"schema_version":1,"run_id":target["run_id"],"mode":target["mode"],
             "source_sha256":facts,"qualification":results,"hosted_edge_deployment":False}
    if args.report:
        report=Path(args.report)
        with report.open("x",encoding="utf-8") as stream:
            json.dump(receipt,stream,indent=2)
            stream.write("\n")
        print(json.dumps({"schema_version":1,"run_id":target["run_id"],"mode":target["mode"],
                          "report":str(report.resolve()),"passed":True}))
    else:
        print(json.dumps(receipt))


if __name__=="__main__":
    try:
        main()
    except (ConsumerFailure,runtime.RuntimeErrorSafe) as error:
        raise SystemExit(f"Error: {error}") from None
    except Exception:
        raise SystemExit("Error: consumer qualification failed; sensitive diagnostics withheld.") from None
